/**
 * Canonical, namespace-scoped identifiers for Outcome as a Platform.
 * IDs are opaque strings; this module intentionally has no persistence dependency.
 */
export type EntityKind =
  | "tenant" | "workspace" | "organization" | "actor" | "intent"
  | "outcome" | "initiative" | "capability" | "execution" | "evidence"
  | "contract" | "policy" | "task" | "metric";

export type TenantId = EntityId<"tenant">;

export type EntityId<K extends EntityKind = EntityKind> = string & {
  readonly __entityKind: K;
};

export interface IdentifierIssue {
  code: "ID_REQUIRED" | "ID_INVALID" | "ID_KIND_MISMATCH";
  path: string;
  message: string;
}

const ID_PATTERN = /^[a-z][a-z0-9]*(?:_[a-z0-9]+)*_[a-z0-9]{3,64}$/;

export function parseEntityId<K extends EntityKind>(
  kind: K,
  value: unknown,
  path = "id",
): EntityId<K> {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new IdentifierValidationError({
      code: "ID_REQUIRED", path, message: "Identifier must be a non-empty string.",
    });
  }
  if (value !== value.trim() || !ID_PATTERN.test(value)) {
    throw new IdentifierValidationError({
      code: "ID_INVALID", path,
      message: "Identifier must be canonical: lowercase namespace and 3–64 lowercase alphanumeric suffix characters separated by underscores.",
    });
  }
  const prefix = value.split("_")[0];
  if (prefix !== kind) {
    throw new IdentifierValidationError({
      code: "ID_KIND_MISMATCH", path,
      message: `Expected "${kind}" identifier; received "${prefix}".`,
    });
  }
  return value as EntityId<K>;
}

export class IdentifierValidationError extends Error {
  readonly issue: IdentifierIssue;
  constructor(issue: IdentifierIssue) {
    super(issue.message);
    this.name = "IdentifierValidationError";
    this.issue = issue;
  }
}

/** IDs generated by clients remain deterministic when an external key is supplied. */
export function canonicalId<K extends EntityKind>(
  kind: K,
  externalKey: string,
): EntityId<K> {
  const normalized = externalKey.normalize("NFKD").replace(/[\\u0300-\\u036f]/g, "").trim().toLowerCase()
    .replace(/[^a-z0-9]+/g, "_").replace(/^_+|_+$/g, "");
  if (normalized.length < 3) {
    throw new IdentifierValidationError({
      code: "ID_INVALID", path: "externalKey",
      message: "External key must yield at least three alphanumeric characters.",
    });
  }
  return parseEntityId(kind, `${kind}_${normalized.slice(0, 64)}`);
}
